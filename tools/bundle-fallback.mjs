/*
 * Fallback bundler.
 *
 * `npm run build` (esbuild) is the supported path and produces a smaller file.
 * This script exists for environments where the installed esbuild binary does
 * not match the host platform — it compiles `src/` with tsc and links the
 * emitted CommonJS modules into the single `main.js` Obsidian expects.
 *
 *   node tools/bundle-fallback.mjs
 */
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, readdirSync, writeFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outDir = mkdtempSync(path.join(tmpdir(), 'obsidian-issues-'));

const tsc = path.join(
  root,
  'node_modules',
  'typescript',
  'bin',
  'tsc',
);

try {
  execFileSync(
    process.execPath,
    [
      tsc,
      path.join(root, 'src', 'main.ts'),
      '--outDir', outDir,
      '--module', 'commonjs',
      '--moduleResolution', 'node',
      '--target', 'ES2021',
      '--lib', 'ES2021,DOM',
      '--skipLibCheck',
      '--strict',
    ],
    { stdio: 'inherit', cwd: root },
  );

  const modules = readdirSync(outDir)
    .filter((file) => file.endsWith('.js'))
    .map((file) => ({
      name: path.basename(file, '.js'),
      code: readFileSync(path.join(outDir, file), 'utf8'),
    }))
    .sort((a, b) => a.name.localeCompare(b.name));

  if (!modules.some((m) => m.name === 'main')) {
    throw new Error('tsc did not emit a main module');
  }

  const factories = modules
    .map(
      ({ name, code }) =>
        `__modules[${JSON.stringify(name)}] = function (module, exports, require) {\n${code}\n};`,
    )
    .join('\n\n');

  const bundle = `/*
THIS IS A GENERATED/BUNDLED FILE
Source: src/
Built by tools/bundle-fallback.mjs (tsc + CommonJS linker).
Run \`npm run build\` for the standard esbuild output.
*/
'use strict';

var __obsidian = require('obsidian');
var __modules = {};
var __cache = {};

function __require(id) {
  if (id === 'obsidian') return __obsidian;
  var key = String(id).replace(/^\\.\\//, '').replace(/\\.js$/, '');
  if (Object.prototype.hasOwnProperty.call(__cache, key)) return __cache[key].exports;
  var factory = __modules[key];
  if (!factory) throw new Error('Unknown module: ' + id);
  var module = { exports: {} };
  __cache[key] = module;
  factory(module, module.exports, __require);
  return module.exports;
}

${factories}

module.exports = __require('main');
`;

  writeFileSync(path.join(root, 'main.js'), bundle);
  console.log(`Wrote main.js (${(bundle.length / 1024).toFixed(1)} kB, ${modules.length} modules)`);
} finally {
  rmSync(outDir, { recursive: true, force: true });
}
